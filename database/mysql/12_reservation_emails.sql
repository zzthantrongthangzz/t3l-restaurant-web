CREATE TABLE IF NOT EXISTS reservation_emails (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  reservation_id BIGINT NOT NULL,
  event_key VARCHAR(100) NOT NULL,
  kind VARCHAR(32) NOT NULL,
  recipient VARCHAR(254) NULL,
  guest_name VARCHAR(120) NOT NULL,
  booking_code VARCHAR(20) NOT NULL,
  starts_at DATETIME(6) NOT NULL,
  guest_count INT NOT NULL,
  area VARCHAR(40) NOT NULL,
  booking_status VARCHAR(40) NOT NULL,
  review_note VARCHAR(500) NULL,
  status VARCHAR(32) NOT NULL,
  attempts INT NOT NULL,
  created_at DATETIME(6) NOT NULL,
  next_attempt_at DATETIME(6) NULL,
  last_attempt_at DATETIME(6) NULL,
  completed_at DATETIME(6) NULL,
  last_error VARCHAR(80) NULL,
  CONSTRAINT uk_reservation_email_event UNIQUE (event_key),
  CONSTRAINT fk_reservation_emails_reservation FOREIGN KEY (reservation_id) REFERENCES reservations(id) ON DELETE CASCADE,
  INDEX ix_reservation_emails_ready (status, next_attempt_at, id),
  INDEX ix_reservation_emails_booking (reservation_id, id),
  INDEX ix_reservation_emails_in_progress (status, last_attempt_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
